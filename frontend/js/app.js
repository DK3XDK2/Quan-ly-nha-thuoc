window.getValidMedicineImage = function(item) {
    if (!item) return window.DEFAULT_MEDICINE_ICON;
    if (typeof item === 'string') {
        const name = item.toLowerCase();
        for (const [key, url] of Object.entries(window.VIETNAM_DRUG_IMAGES)) {
            if (name.includes(key.toLowerCase())) return url;
        }
        return window.DEFAULT_MEDICINE_ICON;
    }
    const raw = item.imageUrl || item.image || item.hinhAnh;
    if (raw && typeof raw === 'string' && raw.startsWith('https://cdn.nhathuoclongchau.com.vn/v1/static/')) {
        return raw;
    }
    const name = (item.name || item.tenThuoc || '').toLowerCase();
    for (const [key, url] of Object.entries(window.VIETNAM_DRUG_IMAGES)) {
        if (name.includes(key.toLowerCase())) {
            return url;
        }
    }
    return (raw && typeof raw === 'string' && !raw.includes('/unsafe/') && !raw.includes('unsplash.com') && !raw.includes('data:image/svg') && !raw.includes('Chưa có ảnh')) ? raw : window.DEFAULT_MEDICINE_ICON;
};

window.goToProductDetail = function(productId) {
    if (productId !== undefined && productId !== null && productId !== '') {
        try {
            localStorage.setItem('selectedProductId', String(productId));
        } catch(e){}
        let path = window.location.pathname.toLowerCase();
        let prefix = '';
        if (path.includes('/customer') || path.includes('/admin')) {
            prefix = '../public/';
        } else if (path.includes('/public')) {
            prefix = '';
        } else if (path.includes('/pages/')) {
            prefix = 'public/';
        } else {
            prefix = 'pages/public/';
        }
        window.location.href = `${prefix}shop-detail.html?id=${encodeURIComponent(productId)}`;
    }
};

